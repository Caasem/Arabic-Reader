// After restoring a backup, removes the votes of every install the live system had already deleted
// (docs/specs/crowd-sense-ranking.md, section 12.1). Run it before letting traffic back in.
//
//   wrangler d1 execute <db> --remote --command "SELECT installId FROM deletions" --json > ledger.json
//   (restore the backup)
//   node crowd-server/scripts/replay-deletions.mjs ledger.json > replay.sql
//   wrangler d1 execute <db> --remote --file replay.sql
//
// The input is the JSON `wrangler d1 execute --json` prints, or a plain array of install ids.
import { readFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) {
  console.error('Usage: node crowd-server/scripts/replay-deletions.mjs <ledger.json>');
  process.exit(1);
}

const data = JSON.parse(readFileSync(file, 'utf8'));
const rows = Array.isArray(data) && typeof data[0] === 'string' ? data.map((installId) => ({ installId })) : (data[0]?.results ?? data);
const ids = [...new Set(rows.map((r) => r.installId))];
const KEY = /^[a-z2-7]{10,32}$/;
const bad = ids.filter((id) => !KEY.test(id));
if (bad.length) {
  console.error(`Refusing: ${bad.length} ids are not install ids, for example ${bad[0]}`);
  process.exit(1);
}

const today = new Date().toISOString().slice(0, 10);
const lines = ['-- Generated by scripts/replay-deletions.mjs'];
for (const id of ids) {
  lines.push(`DELETE FROM votes WHERE installId = '${id}';`);
  lines.push(`DELETE FROM installs WHERE installId = '${id}';`);
  lines.push(`INSERT OR IGNORE INTO deletions (installId, deletedAt) VALUES ('${id}', '${today}');`);
}
console.log(lines.join('\n'));
console.error(`Replayed ${ids.length} deletions`);
